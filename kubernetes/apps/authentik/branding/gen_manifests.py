"""Regenerates manifests/branding.yaml from the *.svg sources here.

ConfigMap keys cannot contain '/', so each asset is a flat key and the
Helm values mount them one by one (subPath) into
/web/dist/assets/desert-bluffs/<key> on the authentik server pod. The
Tofu brand resource references the resulting /static/dist/... paths.
"""

import base64
import io
import pathlib

import cairosvg

HERE = pathlib.Path(__file__).parent
OUT = HERE.parent / "manifests" / "branding.yaml"

# (key, svg source, render width)
ASSETS = [
    ("logo-light.svg", "logo-light.svg", 1080),
    ("logo-dark.svg", "logo-dark.svg", 1080),
    ("favicon.svg", "favicon.svg", 256),
    # Flow backgrounds are injected into the page via an <img> tag, so the
    # served file must be raster rather than SVG.
    ("background.png", "background.svg", 1920),
]


def main() -> None:
    lines = [
        "# Generated by branding/gen-manifests.sh; edit the *.svg sources instead.",
        "# Mounted read-only into the authentik server pod under",
        "# /web/dist/assets/desert-bluffs/ (see values.yaml) so the brand",
        "# fields in authentik/brand.tf can use /static/dist/... paths.",
        "apiVersion: v1",
        "kind: ConfigMap",
        "metadata:",
        "  name: authentik-branding",
        "data:",
    ]
    for key, svg, width in ASSETS:
        src = HERE / svg
        if key.endswith(".png"):
            png = io.BytesIO()
            cairosvg.svg2png(url=str(src), write_to=png, output_width=width)
            b64 = base64.b64encode(png.getvalue()).decode()
            lines += [f"  {key}: |"]
            lines += ["    " + b64[i : i + 76] for i in range(0, len(b64), 76)]
        else:
            lines += [f"  {key}: |"]
            lines += ["    " + l for l in src.read_text().splitlines()]
            # PNG siblings for raster-only contexts (e.g. link previews).
            png_key = key.rsplit(".", 1)[0] + ".png"
            png = io.BytesIO()
            cairosvg.svg2png(url=str(src), write_to=png, output_width=width)
            b64 = base64.b64encode(png.getvalue()).decode()
            lines += [f"  {png_key}: |"]
            lines += ["    " + b64[i : i + 76] for i in range(0, len(b64), 76)]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
